"""Generate src/components/intro/sloganGlyphs.ts: Dancing Script 700 outlines for the intro slogan.

Each grapheme becomes one or more "strokes" (base letter, then each accent component as
its own short stroke) so the intro can write them in pen order. Run from the repo root:
    python3 scripts/gen-slogan-glyphs.py      (needs: pip install fonttools; npm i)
Coordinates are font units (1000/em), y down, baseline at y=0.
"""
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

SLOGAN = 'Trọ an tâm · Nâng tầm cuộc sống'
BASE = 'node_modules/@fontsource/dancing-script/files/dancing-script-{}-700-normal.woff'
fonts = [TTFont(BASE.format(n)) for n in ('latin', 'latin-ext', 'vietnamese')]


def path_of(font, name, dx, dy=0):
    gs = font.getGlyphSet()
    pen = SVGPathPen(gs, lambda v: f'{round(v, 1):g}')
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, dx, -dy)))
    return pen.getCommands()


x = 0
glyphs = []
for ch in SLOGAN:
    font = next(f for f in fonts if ord(ch) in f.getBestCmap())
    name = font.getBestCmap()[ord(ch)]
    adv = font['hmtx'][name][0]
    g = font['glyf'][name]
    strokes = []
    if g.isComposite():
        for i, c in enumerate(g.components):
            d = path_of(font, c.glyphName, x + c.x, c.y)
            if d:
                strokes.append({'d': d, 'accent': i > 0})
    else:
        d = path_of(font, name, x)
        if d:
            strokes.append({'d': d, 'accent': False})
    glyphs.append({'ch': ch, 'strokes': strokes})
    x += adv

out = ('// Generated by scripts/gen-slogan-glyphs.py from Dancing Script 700 (OFL). Do not edit.\n'
       '// Font units (1000/em), y down, baseline y=0.\n'
       f'export const SLOGAN_WIDTH = {x}\n'
       'export const SLOGAN_TOP = -1000\nexport const SLOGAN_BOTTOM = 330\n'
       'export type SloganStroke = { d: string; accent: boolean }\n'
       'export const SLOGAN_GLYPHS: { ch: string; strokes: SloganStroke[] }[] = '
       + json.dumps(glyphs, ensure_ascii=False, indent=1) + '\n')
open('src/components/intro/sloganGlyphs.ts', 'w').write(out)
print('width', x)
